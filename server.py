"""Optional local Flask/SQLite mode. The public static app uses browser storage."""
from datetime import date
from contextlib import contextmanager
from pathlib import Path
import json
import math
import os
import sqlite3
from flask import Flask, abort, jsonify, request, send_from_directory

ROOT = Path(__file__).resolve().parent


def validate(data):
    if not isinstance(data, dict) or data.get('version') != 1:
        raise ValueError('Choose a valid version 1 backup.')
    blocks, readings, settings = data.get('blocks'), data.get('readings'), data.get('settings')
    if not isinstance(blocks, list) or not isinstance(readings, list) or not isinstance(settings, dict):
        raise ValueError('Missing blocks, readings or settings.')
    if len(blocks) > 100 or len(readings) > 20000:
        raise ValueError('Workspace exceeds the supported size.')
    ids, names, reading_ids, pairs = set(), set(), set(), set()
    for b in blocks:
        if not isinstance(b, dict):
            raise ValueError('Invalid block.')
        name, residents, ident = b.get('name'), b.get('residents'), b.get('id')
        if not isinstance(name, str) or not name.strip() or len(name) > 60 or name.strip().lower() in names or type(residents) is not int or not 1 <= residents <= 10000 or not isinstance(ident, str) or not ident or ident in ids:
            raise ValueError('Every block needs a unique name and 1–10,000 residents.')
        ids.add(ident)
        names.add(name.strip().lower())
    for r in readings:
        if not isinstance(r, dict):
            raise ValueError('Invalid reading.')
        ident, block_id, day, value, note = (r.get(k) for k in ('id', 'blockId', 'date', 'value', 'note'))
        try:
            valid_day = isinstance(day, str) and date.fromisoformat(day).isoformat() == day and day <= date.today().isoformat()
        except ValueError:
            valid_day = False
        if not valid_day or not isinstance(ident, str) or not ident or ident in reading_ids or block_id not in ids or (block_id, day) in pairs or type(value) not in (int, float) or not math.isfinite(value) or not 0 <= value <= 1e10 or not isinstance(note, str) or len(note) > 240:
            raise ValueError('Check reading dates, values, parents and duplicates.')
        reading_ids.add(ident)
        pairs.add((block_id, day))
    for key, lower, upper in [('tariff', 0, 100), ('target', 1, 1e7), ('carbon', 0, 5)]:
        v = settings.get(key)
        if type(v) not in (int, float) or not math.isfinite(v) or not lower <= v <= upper:
            raise ValueError('Invalid energy assumptions.')
    return data


def create_app(database=None):
    app = Flask(__name__, static_folder=None)
    app.config.update(MAX_CONTENT_LENGTH=6_000_000, DATABASE=str(database or ROOT / 'workspace.sqlite3'))

    @contextmanager
    def connect():
        db = sqlite3.connect(app.config['DATABASE'])
        try:
            with db:
                db.execute('CREATE TABLE IF NOT EXISTS workspace (id INTEGER PRIMARY KEY CHECK(id=1), payload TEXT NOT NULL)')
                yield db
        finally:
            db.close()

    @app.after_request
    def headers(response):
        response.headers['X-Content-Type-Options'] = 'nosniff'
        response.headers['Cache-Control'] = 'no-store'
        return response

    @app.route('/api/state', methods=['GET', 'PUT'])
    def workspace():
        if request.method == 'PUT':
            if request.headers.get('Origin') not in (None, request.host_url.rstrip('/')):
                return jsonify(error='Same-origin requests only.'), 403
            if not request.is_json:
                return jsonify(error='Send application/json.'), 415
            try:
                payload = validate(request.get_json(silent=True))
            except (ValueError, TypeError, KeyError):
                return jsonify(error='Invalid workspace. Check names, dates, duplicates, residents and settings.'), 400
            with connect() as db:
                db.execute('INSERT INTO workspace VALUES(1,?) ON CONFLICT(id) DO UPDATE SET payload=excluded.payload', (json.dumps(payload, allow_nan=False),))
            return jsonify(saved=True)
        with connect() as db:
            row = db.execute('SELECT payload FROM workspace WHERE id=1').fetchone()
            if not row:
                payload = json.loads((ROOT / 'sample-data.json').read_text())
                # Fresh dates are generated by the JS static demo; backend sample dates
                # are fixed for reproducibility. An empty start is always available.
                db.execute('INSERT INTO workspace VALUES(1,?)', (json.dumps(payload),))
                return jsonify(payload)
        return jsonify(json.loads(row[0]))

    @app.get('/config.js')
    def config():
        return app.response_class((ROOT / 'config.js').read_text().replace('backend:false', 'backend:true'), mimetype='text/javascript')

    @app.get('/')
    @app.get('/<path:filename>')
    def files(filename='index.html'):
        if filename not in {'index.html', 'styles.css', 'app.js', 'core.js', 'favicon.svg'}:
            abort(404)
        return send_from_directory(ROOT, filename)

    return app


if __name__ == '__main__':
    create_app().run(host='127.0.0.1', port=int(os.environ.get('PORT', '5174')), debug=False)
